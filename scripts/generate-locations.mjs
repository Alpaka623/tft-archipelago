// Generates the location catalog from src/data/traits.json (run after `npm run import:tft-data`).
// Writes one JSON catalog for the app and a Python mirror for the APWorld, so both always agree.
//
//   npm run generate:locations

import { readFile, writeFile } from 'node:fs/promises'

const TRAITS_PATH = 'src/data/traits.json'
const CATALOG_PATH = 'src/data/location-catalog.json'
const PYTHON_PATH = 'worlds/tft_archipelago/location_catalog.py'
const BASE_LOCATION_ID = 7431000

// Major trait checks use the second-highest breakpoint, capped so 9/11-unit breakpoints stay
// reachable. Traits whose highest breakpoint is 2 or lower are unique/pair traits and skipped.
const MAJOR_TRAIT_BREAKPOINT_CAP = 7
const MAJOR_TRAIT_MIN_TOP_BREAKPOINT = 3
const MAJOR_CHAMPION_COST = 5
const FILLER_ONLY_MIN_COST = 4

const EXTRA_MINOR_CHECKS = [
  { name: 'Have 3 Traits active', condition: { type: 'activeTraitCount', minimumActiveTraits: 3 } },
  { name: 'Have 5 Traits active', condition: { type: 'activeTraitCount', minimumActiveTraits: 5 } },
  { name: 'Reach 50 gold', condition: { type: 'gold', minimumGold: 50 } },
  { name: 'Reach 80 gold', condition: { type: 'gold', minimumGold: 80 } },
  { name: 'Reach 100 gold', condition: { type: 'gold', minimumGold: 100 } },
  { name: 'Reach level 8', condition: { type: 'level', minimumLevel: 8 } },
  { name: 'Reach level 9', condition: { type: 'level', minimumLevel: 9 } },
  { name: 'Eliminate a player', condition: { type: 'playersEliminated', minimumPlayers: 1 } },
  { name: 'Reach Stage 5', condition: { type: 'stage', minimumStage: 5 } },
]

const byName = (left, right) => left.name.localeCompare(right.name)

function pickMajorTraitBreakpoint(breakpoints) {
  const sorted = [...breakpoints].sort((left, right) => left - right)
  const top = sorted[sorted.length - 1]
  if (top === undefined || top < MAJOR_TRAIT_MIN_TOP_BREAKPOINT) return null
  const target = sorted.length >= 2 ? sorted[sorted.length - 2] : top
  if (target <= MAJOR_TRAIT_BREAKPOINT_CAP) return target
  return sorted.filter(value => value <= MAJOR_TRAIT_BREAKPOINT_CAP).pop() ?? null
}

function buildCatalog(traitsData) {
  const aliases = traitsData.championAliases ?? {}
  const champions = Object.entries(traitsData.championNames ?? {})
    .filter(([apiName]) => aliases[apiName] === undefined)
    .map(([apiName, name]) => ({ apiName, name, cost: Number(traitsData.championCosts?.[apiName]) }))
    .filter(champion => Number.isFinite(champion.cost))

  const majorTraits = Object.values(traitsData.traitNames ?? {})
    .map(name => ({ name, minimumActive: pickMajorTraitBreakpoint(traitsData.traitBreakpoints?.[name] ?? []) }))
    .filter(trait => trait.minimumActive !== null)
    .sort(byName)

  const majorChampions = champions.filter(champion => champion.cost === MAJOR_CHAMPION_COST).sort(byName)
  const starChampions = [...champions].sort((left, right) => left.cost - right.cost || byName(left, right))

  const entries = [
    ...majorTraits.map(trait => ({
      name: `Reach Top 4 with ${trait.minimumActive} ${trait.name} active`,
      category: 'major',
      condition: { type: 'trait', trait: trait.name, minimumActive: trait.minimumActive },
    })),
    ...majorChampions.map(champion => ({
      name: `Reach Top 4 with ${champion.name} on your board`,
      category: 'major',
      condition: { type: 'champion', championId: champion.apiName },
    })),
    ...starChampions.flatMap(champion => [2, 3].map(starLevel => ({
      name: `Field a ${starLevel}-Star ${champion.name}`,
      category: 'minor',
      condition: { type: 'champion', championId: champion.apiName, minimumStarLevel: starLevel, requiresPlayerCombat: true },
      // 3-star 4- and 5-costs are rarely possible: nice optional rewards only, never progression
      ...(starLevel === 3 && champion.cost >= FILLER_ONLY_MIN_COST ? { fillerOnly: true } : {}),
    }))),
    ...EXTRA_MINOR_CHECKS.map(check => ({ ...check, category: 'minor' })),
  ]

  const names = new Set()
  return entries.map((entry, index) => {
    if (names.has(entry.name)) throw new Error(`Duplicate location name: ${entry.name}`)
    names.add(entry.name)
    return { id: BASE_LOCATION_ID + index, ...entry }
  })
}

function toPython(catalog, metadata) {
  const json = JSON.stringify(catalog, null, 1)
  if (json.includes("'''")) throw new Error('Catalog JSON cannot be embedded in a Python string')
  return `# Generated by scripts/generate-locations.mjs from src/data/traits.json - do not edit by hand.
# Set ${metadata.setNumber}: ${catalog.length} locations
import json

LOCATION_CATALOG = json.loads(r'''${json}''')
`
}

const traitsData = JSON.parse(await readFile(TRAITS_PATH, 'utf8'))
const catalog = buildCatalog(traitsData)
await writeFile(CATALOG_PATH, `${JSON.stringify(catalog, null, 2)}\n`, 'utf8')
await writeFile(PYTHON_PATH, toPython(catalog, traitsData.metadata ?? {}), 'utf8')

const majors = catalog.filter(entry => entry.category === 'major')
console.log(`Set ${traitsData.metadata?.setNumber}: ${catalog.length} locations (${majors.length} major, ${catalog.length - majors.length} minor)`)
console.log(`IDs ${catalog[0]?.id} - ${catalog[catalog.length - 1]?.id}`)
console.log(`Wrote ${CATALOG_PATH} and ${PYTHON_PATH}`)
