import locationCatalog from './location-catalog.json'

export type LocationCondition =
  | { type: 'champion'; championId: string; minimumStarLevel?: number; requiresPlayerCombat?: boolean }
  | { type: 'trait'; trait: string; minimumActive: number }
  | { type: 'unit'; cost: number; minimumStarLevel: number; requiresPlayerCombat?: boolean }
  | { type: 'activeTraitCount'; minimumActiveTraits: number; requiresPlayerCombat?: boolean }
  | { type: 'gold'; minimumGold: number }
  | { type: 'playerCombatWins'; minimumWins: number; consecutive: boolean }
  // Match-end values from the Riot client's match history (Electron)
  | { type: 'level'; minimumLevel: number }
  | { type: 'stage'; minimumStage: number }

export type LocationCategory = 'major' | 'minor'

export interface LocationCheck {
  id: number
  name: string
  category: LocationCategory
  condition: LocationCondition
  // Rarely achievable: the APWorld only places one-time items and traps here
  fillerOnly?: boolean
}

// Generated by `npm run generate:locations` from src/data/traits.json; the APWorld reads the same
// catalog (worlds/tft_archipelago/location_catalog.py), so ids and conditions always match.
export const LOCATION_CHECKS: LocationCheck[] = locationCatalog as LocationCheck[]
export const MAJOR_LOCATION_CHECKS = LOCATION_CHECKS.filter(check => check.category === 'major')
export const MINOR_LOCATION_CHECKS = LOCATION_CHECKS.filter(check => check.category === 'minor')
